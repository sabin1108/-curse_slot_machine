const bulletPct = (id: string, percent: number) => ({
  id,
  type: 'combat.action_amount.add_pct' as const,
  params: { action: 'bullet' as const, percent },
})

const bulletAdd = (id: string, amount: number) => ({
  id,
  type: 'combat.action_amount.add' as const,
  params: { action: 'bullet' as const, amount },
})

